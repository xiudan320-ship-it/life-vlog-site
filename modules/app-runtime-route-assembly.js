export function createPageControllerRegistry() {
  const pageControllers = {};
  const secretController = createLazyControllerProxy(pageControllers, "secret");
  const wardrobeController = createLazyControllerProxy(pageControllers, "wardrobe");
  const recipeController = createLazyControllerProxy(pageControllers, "recipe");
  const wishlistController = createLazyControllerProxy(pageControllers, "wishlist");
  const shoppingController = createLazyControllerProxy(pageControllers, "shopping");
  const wishlistHubController = createLazyControllerProxy(pageControllers, "wishlistHub");
  const weekendController = createLazyControllerProxy(pageControllers, "weekend");
  const familySettingsController = createLazyControllerProxy(pageControllers, "familySettings");
  const offlineSettingsController = createLazyControllerProxy(pageControllers, "offlineSettings");
  const dataSafetyController = createLazyControllerProxy(pageControllers, "dataSafety");
  const callLoaded = (controller, method, ...args) => (
    controller.isLoaded ? controller.get()[method]?.(...args) : undefined
  );

  return Object.freeze({
    pageControllers,
    secretController,
    wardrobeController,
    recipeController,
    wishlistController,
    shoppingController,
    wishlistHubController,
    weekendController,
    familySettingsController,
    offlineSettingsController,
    dataSafetyController,
    callLoaded,
  });
}

